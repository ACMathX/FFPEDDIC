classdef C_LegendrePolynomial < handle
    properties
        implemented_limit
    end

    methods
        function [ self ] = C_LegendrePolynomial( )
            self.implemented_limit = 36;
        end

        function [ P ] = get_polynomial( self, n )
            if n < self.implemented_limit
                P = eval( sprintf( 'self.order_%02d_polynomial', n ) );
            else
                factor_1 = 2 * n - 1;
                factor_2 = n - 1;
                P_n_minus_1 = self.get_polynomial( n - 1 );
                P_n_minus_2 = self.get_polynomial( n - 2 );
                P = @( x ) ( factor_1 .* x .* P_n_minus_1( x ) - factor_2 * P_n_minus_2( x ) ) / n;
            end
        end

        function [ C ] = get_polynomial_coefficient( self, n )
            if n < self.implemented_limit
                C = eval( sprintf( 'self.order_%02d_polynomial_coefficient', n ) );
            else
                factor_1 = 2 * n - 1;
                factor_2 = n - 1;
                C_n_minus_1 = self.get_polynomial_coefficient( n - 1 );
                C_n_minus_2 = self.get_polynomial_coefficient( n - 2 );
                C_n_minus_1( 1, : ) = C_n_minus_1( 1, : ) + 1;
                if size( C_n_minus_1, 2 ) == size( C_n_minus_2, 2 )
                    C_n_minus_1 = [ C_n_minus_1, [ 0; 0 ] ];
                end
                C = [ C_n_minus_1( 1, : );
                      ( factor_1 .* C_n_minus_1( 2, : ) - factor_2 .* [ 0, C_n_minus_2( 2, : ) ] ) / n ];
            end
        end

        function [ C ] = get_polynomial_coefficient_special( self, n )
            if n < self.implemented_limit
                C = eval( sprintf( 'self.order_%02d_polynomial_coefficient_special', n ) );
            else
                factor_1 = 2 * n - 1;
                factor_2 = n - 1;
                C_n_minus_1 = self.get_polynomial_coefficient_special( n - 1 );
                C_n_minus_2 = self.get_polynomial_coefficient_special( n - 2 );
                C = [ 0 : n;
                      ( 2 .* factor_1 .* [ 0, C_n_minus_1( 2, : ) ] - factor_1 .* [ C_n_minus_1( 2, : ), 0 ] - factor_2 .* [ C_n_minus_2( 2, : ), 0, 0 ] ) / n ];
            end
        end
    end

